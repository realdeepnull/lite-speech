/**
 * Markdown rendering for the quality harness.
 *
 * Two documents come out of a sweep. `quality.md` is the table a reader checks; `listening.md` is the
 * protocol a human follows to fill in the one field the harness refuses to invent.
 */
import { readdir, readFile } from "node:fs/promises";
import { join } from "node:path";

import type { QualityReport } from "./schema.js";

/** One row of the quality table, so the CLI can log without re-reading the files. */
export function renderQualityRow(report: QualityReport): string {
  const total = report.cases.length;
  const limited = report.cases.filter((entry) => entry.expectation === "known-limitation").length;
  const ratios = report.cases
    .map((entry) => entry.stream.samplesRatio)
    .filter((value) => Number.isFinite(value));
  const worst = ratios.length > 0 ? Math.min(...ratios) : Number.NaN;
  return (
    `${report.dtype} (${report.device}): ${String(total)} cases, ${String(limited)} known limitations, ` +
    `worst stream/full ratio ${Number.isFinite(worst) ? worst.toFixed(3) : "n/a"}`
  );
}

/** Renders every quality report in `directory` as one Markdown document. */
export async function renderQualityMarkdown(directory: string): Promise<string> {
  const files = (await readdir(directory))
    .filter((file) => /^quality-.*\.json$/u.test(file))
    .sort();
  const reports: QualityReport[] = [];
  for (const file of files) {
    reports.push(JSON.parse(await readFile(join(directory, file), "utf8")) as QualityReport);
  }
  return renderReports(reports);
}

/** Renders the reports. Kept separable so a test can render a fixture without a directory. */
function renderReports(reports: readonly QualityReport[]): string {
  const lines = [
    "# Quality sweep",
    "",
    "Generated by `npm run quality:node --workspace @lite-speech/bench-quality`. Every number below",
    "comes from a committed JSON report in this directory.",
    "",
  ];

  for (const report of reports) {
    lines.push(
      `## ${report.dtype} on ${report.device} (${report.runtime})`,
      "",
      `Model \`${report.model.id}@${report.model.revision}\`, temperature ${String(report.temperature)}.`,
      "",
      "| case | expectation | full s | stream s | stream/full | chunks | frame samples | step ratio (full) |",
      "| ---- | ----------- | ------ | -------- | ----------- | ------ | ------------- | ----------------- |",
    );
    for (const entry of report.cases) {
      lines.push(
        `| ${entry.id} | ${entry.expectation} | ${entry.full.seconds.toFixed(2)} | ` +
          `${entry.stream.seconds.toFixed(2)} | ${entry.stream.samplesRatio.toFixed(3)} | ` +
          `${String(entry.stream.chunks)} | ${entry.stream.frameSamples.join(", ")} | ` +
          `${entry.stream.fullStepRatio.toFixed(2)} |`,
      );
    }
    lines.push("");
    if (report.determinism !== undefined) {
      lines.push(
        report.determinism.identical
          ? `Repeat synthesis of \`${report.determinism.caseId}\` with the same dtype was **byte-identical**, so each run below is reproducible — but that says nothing about whether the quantized graph follows the same *trajectory* as fp32, which is what the correlation column measures.`
          : `Repeat synthesis of \`${report.determinism.caseId}\` **differed** (max sample difference ${report.determinism.maxDiff.toFixed(4)}): this configuration is not deterministic at this temperature, so no sample-by-sample comparison in this report can be attributed to quantization.`,
        "",
      );
    }
    if (report.temperature === 0) {
      lines.push(
        "| case | SNR vs fp32 (dB) | correlation | max diff | length delta |",
        "| ---- | ---------------- | ----------- | -------- | ------------ |",
      );
      for (const entry of report.cases) {
        if (entry.versusReference === undefined) {
          continue;
        }
        const snr =
          typeof entry.versusReference.snrDb === "number"
            ? entry.versusReference.snrDb.toFixed(2)
            : entry.versusReference.snrDb;
        lines.push(
          `| ${entry.id} | ${String(snr)} | ${entry.versusReference.correlation.toFixed(3)} | ` +
            `${entry.versusReference.maxDiff.toFixed(4)} | ${String(entry.versusReference.lengthDelta)} |`,
        );
      }
      lines.push(
        "",
        "A negative SNR next to a correlation near `0` is **not** quantization noise: the quantized",
        "graph produced a different performance of the same sentence (different prosody, a different",
        "stop point), and subtracting two different utterances yields a negative ratio by",
        "construction. Only a correlation near `1` makes the SNR a measure of added noise. The",
        "practical consequence for dtype selection is that `q4`/`q4f16` must be judged by listening,",
        "not by waveform distance — which is why the listening protocol exists and its score is",
        "still `pending`.",
        "",
      );
    }
    if (report.notes.length > 0) {
      lines.push(...report.notes.map((note) => `- ${note}`), "");
    }
  }

  lines.push(
    "## Listening",
    "",
    "The listening score is **pending** by design: the harness produces the audio and the protocol",
    "(`listening.md`) but does not invent a number. See that file for the rating procedure.",
    "",
  );
  return `${lines.join("\n")}\n`;
}

/** The blind protocol a human follows to produce a MOS-style score. */
export function renderListeningProtocol(): string {
  return [
    "# Listening protocol",
    "",
    "The quality harness measures signal properties; it cannot measure whether speech sounds like",
    'speech. This protocol produces the one number it deliberately leaves as `"pending"`.',
    "",
    "## Stimuli",
    "",
    "`audio/` holds one 16-bit mono WAV per case per dtype, named",
    "`<device>-<dtype>-<case>.wav`. They were produced at `temperature: 0`, so replaying the sweep",
    "yields byte-identical files.",
    "",
    "## Procedure",
    "",
    "1. Blind the file names: replace each `-fp32-`, `-q4-`, `-q4f16-` segment with `-A-`, `-B-`, `-C-`",
    "   using a shuffled mapping you keep out of sight until scoring is done.",
    "2. Have at least three raters listen on headphones, in one sitting, in the same order.",
    "3. For each case, rate naturalness on a 1–5 scale (1 = unintelligible, 3 = understandable but",
    "   clearly synthetic, 5 = indistinguishable from a recording).",
    "4. Record the median per case and per dtype, then the mean of the per-case medians.",
    "5. Enter the result as `listening.score` in `quality-node-cpu-<dtype>.json`, and set",
    "   `listening.raters` to the number of raters. Do not change anything else in the report.",
    "",
    "## Reporting",
    "",
    "Quote the score only with its case count, rater count, and hardware, exactly like the latency",
    "tables: a MOS without that context is a number someone made up.",
    "",
  ].join("\n");
}
